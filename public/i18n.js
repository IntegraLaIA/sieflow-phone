function storedLanguage() {
  try {
    return localStorage.getItem('sieflow-phone.lang') || '';
  } catch {
    return '';
  }
}

export function languageSetting() {
  return storedLanguage();
}

function resolveLanguage() {
  const chosen = storedLanguage();
  if (STRINGS[chosen]) return chosen;
  return (navigator.language || 'en').toLowerCase().startsWith('es') ? 'es' : 'en';
}

let lang = resolveLanguage();

export const currentLanguage = () => lang;

export function setLanguage(value) {
  try {
    if (value) localStorage.setItem('sieflow-phone.lang', value);
    else localStorage.removeItem('sieflow-phone.lang');
  } catch {
    // The choice just will not survive a reload.
  }
  lang = resolveLanguage();
  applyI18n();
}

// t('outcomes.missed'), t('online', { n: 2 })
export function t(key, vars = {}) {
  const lookup = (dict) => key.split('.').reduce((node, part) => node?.[part], dict);
  const value = lookup(STRINGS[lang]) ?? lookup(STRINGS.en) ?? key;
  if (typeof value !== 'string') return value;
  return value.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? `{${name}}`));
}

export function has(key) {
  return key.split('.').reduce((node, part) => node?.[part], STRINGS[lang]) !== undefined;
}

export function applyI18n(root = document) {
  if (root === document) document.documentElement.lang = lang;
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll('[data-i18n-title]')) {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute('aria-label', el.title);
  }
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
}
